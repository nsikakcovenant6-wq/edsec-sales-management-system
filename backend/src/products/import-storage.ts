import { ImportValidationError } from "./import-validation.js";

export const PRODUCT_IMPORT_UPLOAD_POLICY = {
  bucket: "edsec-product-imports",
  maxBytes: 10 * 1024 * 1024,
  allowed: [
    { extension: ".csv", mimeTypes: ["text/csv", "application/csv", "text/plain"] },
    { extension: ".xlsx", mimeTypes: ["application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"] },
  ],
  expiresInSeconds: 300,
} as const;

export interface SignedImportUploadRequest {
  file_name: string;
  content_type: string;
  size_bytes: number;
}
export interface SignedImportUploadResponse {
  bucket: "edsec-product-imports";
  object_path: string;
  upload_url: string;
  token: string;
  expires_in: number;
}

export function validateSignedImportUploadRequest(value: unknown): SignedImportUploadRequest {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new ImportValidationError("VALIDATION_ERROR", "Upload request must be an object");
  }
  const input = value as Record<string, unknown>;
  if (typeof input.file_name !== "string" || input.file_name.length < 1 || input.file_name.length > 180 ||
      /[/\\\\]/.test(input.file_name) || input.file_name === "." || input.file_name === "..") {
    throw new ImportValidationError("INVALID_FILE_NAME", "file_name must be a plain file name");
  }
  if (typeof input.content_type !== "string") {
    throw new ImportValidationError("INVALID_CONTENT_TYPE", "content_type is required");
  }
  if (typeof input.size_bytes !== "number" || !Number.isSafeInteger(input.size_bytes) ||
      input.size_bytes < 1 || input.size_bytes > PRODUCT_IMPORT_UPLOAD_POLICY.maxBytes) {
    throw new ImportValidationError("FILE_TOO_LARGE", "File size must be between 1 byte and 10 MiB");
  }
  const extension = input.file_name.slice(input.file_name.lastIndexOf(".")).toLowerCase();
  const policy = PRODUCT_IMPORT_UPLOAD_POLICY.allowed.find((item) => item.extension === extension);
  if (!policy || !policy.mimeTypes.includes(input.content_type as never)) {
    throw new ImportValidationError("UNSUPPORTED_FILE_TYPE", "Only CSV and XLSX files with matching MIME types are accepted");
  }
  return {
    file_name: input.file_name,
    content_type: input.content_type,
    size_bytes: input.size_bytes,
  };
}

/** Object paths are generated by the server and must remain inside the authenticated tenant prefix. */
export function assertTenantImportObjectPath(objectPath: string, businessId: string): void {
  const prefix = `${businessId}/imports/`;
  if (!objectPath.startsWith(prefix) || objectPath.length > 512 ||
      objectPath.includes("..") || objectPath.startsWith("/") || objectPath.includes("\\\\")) {
    throw new ImportValidationError("INVALID_OBJECT_PATH", "Upload object path is outside this business import namespace");
  }
  const file = objectPath.slice(prefix.length);
  if (!file || file.includes("/")) {
    throw new ImportValidationError("INVALID_OBJECT_PATH", "Upload object path must identify one file in the business import namespace");
  }
}
